const lk = (m: Record<string, Map<string, string>>, n: string, id: string | null) =>
  id ? (m[n]?.get(id) ?? '—') : '—';
const DAYS = ['', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday', 'Sunday'];
export const dayName = (d: number) => DAYS[d] ?? '';
const t = (x?: string | null) => (x ? x.slice(0, 5) : '—');
const dt = (iso: string) =>
  new Date(iso).toLocaleString('en-PH', {
    timeZone: 'Asia/Manila',
    dateStyle: 'medium',
    timeStyle: 'short',
  });

